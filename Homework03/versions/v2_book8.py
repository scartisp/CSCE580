BOARD: int = BOTTOM * ((1 << HEIGHT) - 1)
COL_MASKS: List[int] = [((1 << HEIGHT) - 1) << (col * H1) for col in range(WIDTH)]
CENTER: int = COL_MASKS[WIDTH // 2]
